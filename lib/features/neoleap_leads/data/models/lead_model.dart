import '../../domain/entities/lead_entity.dart';

class LeadModel extends LeadEntity {
  const LeadModel({
    required super.id,
    required super.googlePlaceId,
    required super.name,
    super.businessName,
    super.category = 'نشاط تجاري',
    super.phone,
    super.website,
    super.rating,
    super.ratingCount,
    super.formattedAddress,
    required super.latitude,
    required super.longitude,
    super.regionName,
    super.cityName,
    super.villageName,
    super.district,
    super.postalCode,
    super.distanceKm = 0.0,
    super.leadStatus = LeadStatus.discovered,
    super.isSent = false,
    super.sentAt,
    required super.discoveredAt,
    super.lastSeenAt,
  });

  factory LeadModel.fromJson(Map<String, dynamic> json) {
    return LeadModel(
      id: json['id'] as String? ?? json['google_place_id'] as String? ?? DateTime.now().millisecondsSinceEpoch.toString(),
      googlePlaceId: json['google_place_id'] as String? ?? json['googlePlaceId'] as String? ?? json['id'] as String? ?? '',
      name: json['name'] as String? ?? 'منشأة تجارية',
      businessName: json['business_name'] as String? ?? json['businessName'] as String?,
      category: json['category'] as String? ?? 'نشاط تجاري',
      phone: json['phone'] as String?,
      website: json['website'] as String?,
      rating: (json['rating'] as num?)?.toDouble(),
      ratingCount: (json['rating_count'] as num?)?.toInt() ?? (json['ratingCount'] as num?)?.toInt(),
      formattedAddress: json['formatted_address'] as String? ?? json['formattedAddress'] as String? ?? json['address'] as String?,
      latitude: (json['latitude'] as num? ?? 24.7136).toDouble(),
      longitude: (json['longitude'] as num? ?? 46.6753).toDouble(),
      regionName: json['region_name'] as String? ?? json['regionName'] as String?,
      cityName: json['city_name'] as String? ?? json['cityName'] as String?,
      villageName: json['village_name'] as String? ?? json['villageName'] as String?,
      district: json['district'] as String?,
      postalCode: json['postal_code'] as String? ?? json['postalCode'] as String?,
      distanceKm: (json['distance_km'] as num?)?.toDouble() ?? (json['distanceKm'] as num?)?.toDouble() ?? 0.0,
      leadStatus: LeadStatusX.fromCode(json['lead_status'] as String? ?? json['leadStatus'] as String?),
      isSent: json['is_sent'] as bool? ?? json['isSent'] as bool? ?? false,
      sentAt: json['sent_at'] != null ? DateTime.tryParse(json['sent_at'] as String) : (json['sentAt'] != null ? DateTime.tryParse(json['sentAt'] as String) : null),
      discoveredAt: json['discovered_at'] != null ? (DateTime.tryParse(json['discovered_at'] as String) ?? DateTime.now()) : (json['discoveredAt'] != null ? (DateTime.tryParse(json['discoveredAt'] as String) ?? DateTime.now()) : DateTime.now()),
      lastSeenAt: json['last_seen_at'] != null ? DateTime.tryParse(json['last_seen_at'] as String) : (json['lastSeenAt'] != null ? DateTime.tryParse(json['lastSeenAt'] as String) : null),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'google_place_id': googlePlaceId,
      'name': name,
      'business_name': businessName,
      'category': category,
      'phone': phone,
      'website': website,
      'rating': rating,
      'rating_count': ratingCount,
      'formatted_address': formattedAddress,
      'latitude': latitude,
      'longitude': longitude,
      'region_name': regionName,
      'city_name': cityName,
      'village_name': villageName,
      'district': district,
      'postal_code': postalCode,
      'distance_km': distanceKm,
      'lead_status': leadStatus.code,
      'is_sent': isSent,
      'sent_at': sentAt?.toIso8601String(),
      'discovered_at': discoveredAt.toIso8601String(),
      'last_seen_at': lastSeenAt?.toIso8601String(),
    };
  }

  factory LeadModel.fromEntity(LeadEntity entity) {
    return LeadModel(
      id: entity.id,
      googlePlaceId: entity.googlePlaceId,
      name: entity.name,
      businessName: entity.businessName,
      category: entity.category,
      phone: entity.phone,
      website: entity.website,
      rating: entity.rating,
      ratingCount: entity.ratingCount,
      formattedAddress: entity.formattedAddress,
      latitude: entity.latitude,
      longitude: entity.longitude,
      regionName: entity.regionName,
      cityName: entity.cityName,
      villageName: entity.villageName,
      district: entity.district,
      postalCode: entity.postalCode,
      distanceKm: entity.distanceKm,
      leadStatus: entity.leadStatus,
      isSent: entity.isSent,
      sentAt: entity.sentAt,
      discoveredAt: entity.discoveredAt,
      lastSeenAt: entity.lastSeenAt,
    );
  }
}
